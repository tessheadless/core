-- Minimal Lua client for the headless CMS GraphQL API.
--
--   luarocks install luasocket && luarocks install dkjson
--   TESS_URL=http://localhost:8080 lua cms_client.lua
--
-- Lists, searches and fetches posts by slug, shows GraphQL error codes and,
-- when TESS_ADMIN_TOKEN is set, creates + publishes a post and uploads a file.
-- Plain http:// only (luasocket); for https use luasec's `ssl.https` module,
-- which has the same request API.

local http = require("socket.http")
local ltn12 = require("ltn12")
local json = require("dkjson")

local TESS_URL = (os.getenv("TESS_URL") or "http://localhost:8080"):gsub("/+$", "")
local ADMIN_TOKEN = os.getenv("TESS_ADMIN_TOKEN") -- read from the environment only
if ADMIN_TOKEN == "" then ADMIN_TOKEN = nil end

http.TIMEOUT = 15

-- POST raw `body`; returns status code and response body.
local function post(url, body, headers)
  local chunks = {}
  headers["content-length"] = tostring(#body)
  local ok, status = http.request({
    url = url,
    method = "POST",
    headers = headers,
    source = ltn12.source.string(body),
    sink = ltn12.sink.table(chunks),
  })
  if not ok then error("cannot reach " .. TESS_URL .. ": " .. tostring(status), 0) end
  return status, table.concat(chunks)
end

-- Errors raised by gql() are tables { code = ..., message = ... }.
local function gql(query, variables, admin)
  local headers = { ["content-type"] = "application/json" }
  if admin then headers["authorization"] = "Bearer " .. ADMIN_TOKEN end
  local body = json.encode({ query = query, variables = variables or json.decode("{}") })
  local status, raw = post(TESS_URL .. "/graphql", body, headers)
  if status >= 300 then error("HTTP " .. status .. ": " .. raw, 0) end
  local payload, _, err = json.decode(raw)
  if err then error("invalid JSON: " .. err, 0) end
  if payload.errors and #payload.errors > 0 then
    local first = payload.errors[1]
    local code = (first.extensions and first.extensions.code) or "UNKNOWN"
    error({ code = code, message = first.message }, 0)
  end
  return payload.data
end

local function describe(e)
  if type(e) == "table" then return "[" .. e.code .. "] " .. e.message end
  return tostring(e)
end

local POST_CARD = "ref title slug excerpt publishedAt author { name }"

local LIST_POSTS = [[query ListPosts($first: Int!) {
  posts(orderBy: [createdAt_DESC], first: $first) { total items { ]] .. POST_CARD .. [[ } }
}]]

local SEARCH_POSTS = [[query Search($q: String!) {
  searchPosts(query: $q, first: 5) { total items { ]] .. POST_CARD .. [[ } }
}]]

-- Route by slug: ids are encrypted and expire, never put them in URLs.
local POST_BY_SLUG = [[query PostBySlug($slug: String!) {
  posts(where: { slug: $slug }, first: 1) {
    items { ref title slug body tags publishedAt author { name } }
  }
}]]

local CREATE_POST = [[mutation Create($data: PostCreateInput!) { createPost(data: $data) { id ref slug stage } }]]
local PUBLISH_POST = [[mutation Publish($id: ID!) { publishPost(id: $id) { ref slug stage publishedAt } }]]

local function author_name(p)
  if type(p.author) == "table" then return p.author.name end
  return "?"
end

local function post_by_slug(slug)
  return gql(POST_BY_SLUG, { slug = slug }).posts.items[1]
end

local function admin_demo()
  if not ADMIN_TOKEN then
    print("\n(admin) TESS_ADMIN_TOKEN not set: skipping create/publish and media upload")
    return
  end
  local slug = string.format("lua-example-%d-%d", os.time(), math.random(1e6))
  local created = gql(CREATE_POST, { data = {
    title = "Hello from Lua", slug = slug, excerpt = "Created by examples/clients/lua.",
    body = "Draft first, then published.", tags = { "example", "lua" },
  } }, true).createPost
  print(string.format("\n(admin) created draft %s stage=%s ref=%s", created.slug, created.stage, created.ref))
  -- The id is used immediately and never stored.
  local published = gql(PUBLISH_POST, { id = created.id }, true).publishPost
  print(string.format("(admin) published %s stage=%s at %s", published.slug, published.stage, published.publishedAt))

  local status, raw = post(TESS_URL .. "/media/upload?fileName=lua-example.txt",
    "generated by the lua example at " .. os.date("!%Y-%m-%dT%H:%M:%SZ") .. "\n",
    { ["content-type"] = "text/plain", ["authorization"] = "Bearer " .. ADMIN_TOKEN })
  local asset = json.decode(raw) or {}
  if status >= 300 then
    print(string.format("(admin) upload failed (HTTP %d): [%s] %s", status, tostring(asset.code), tostring(asset.error)))
    return
  end
  local url = asset.url
  if url:sub(1, 1) == "/" then url = TESS_URL .. url end
  print(string.format("(admin) uploaded %s (%s, %d bytes) ref=%s\n(admin) download: %s",
    asset.fileName, asset.mimeType, asset.size, asset.ref, url))
end

local function main()
  math.randomseed(os.time())
  local posts = gql(LIST_POSTS, { first = 10 }).posts
  print(posts.total .. " published post(s):")
  for _, p in ipairs(posts.items) do
    print(string.format("  - [%s] %s (/posts/%s) by %s", p.ref, p.title, p.slug, author_name(p)))
  end

  local hits = gql(SEARCH_POSTS, { q = "lambda" }).searchPosts
  local slugs = {}
  for _, p in ipairs(hits.items) do slugs[#slugs + 1] = p.slug end
  print(string.format("\nsearch 'lambda': %d hit(s): %s", hits.total, table.concat(slugs, ", ")))

  if posts.items[1] then
    local slug = posts.items[1].slug
    local post = post_by_slug(slug)
    print(string.format("\nby slug '%s': %s tags=%s\n  %s", slug, post.title, json.encode(post.tags), post.body))
  end
  print("by slug 'does-not-exist': " .. tostring(post_by_slug("does-not-exist")))

  local ok, e = pcall(gql, "query($id: ID!) { post(id: $id) { title } }", { id = "not-a-real-id" })
  if not ok then print("\nexpected error: " .. describe(e)) end
  ok, e = pcall(gql, CREATE_POST, { data = { title = "nope" } })
  if not ok then print("expected error: " .. describe(e)) end

  admin_demo()
end

local ok, err = pcall(main)
if not ok then
  io.stderr:write("error: " .. describe(err) .. "\n")
  os.exit(1)
end

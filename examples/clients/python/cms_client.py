"""Minimal Python client for the headless CMS GraphQL API.

Shows: listing published posts, full-text search, lookup by slug, error
handling via `errors[].extensions.code`, and (with TESS_ADMIN_TOKEN) creating
+ publishing a post and uploading a media file.

    pip install requests
    TESS_URL=http://localhost:8080 python3 cms_client.py
"""
from __future__ import annotations

import os
import sys
import time
from typing import Any

import requests

TESS_URL = os.environ.get("TESS_URL", "http://localhost:8080").rstrip("/")
ADMIN_TOKEN = os.environ.get("TESS_ADMIN_TOKEN")  # read from env only, never hard-code


class GraphQLError(Exception):
    """A GraphQL `errors[]` entry; `code` comes from `extensions.code`."""

    def __init__(self, errors: list[dict[str, Any]]):
        self.errors = errors
        first = errors[0]
        self.code = (first.get("extensions") or {}).get("code", "UNKNOWN")
        super().__init__(f"[{self.code}] {first.get('message')}")


def gql(query: str, variables: dict[str, Any] | None = None, *, admin: bool = False) -> dict[str, Any]:
    headers = {"Content-Type": "application/json"}
    if admin:
        headers["Authorization"] = f"Bearer {ADMIN_TOKEN}"
    resp = requests.post(
        f"{TESS_URL}/graphql",
        json={"query": query, "variables": variables or {}},
        headers=headers,
        timeout=10,
    )
    resp.raise_for_status()
    payload = resp.json()
    if payload.get("errors"):
        raise GraphQLError(payload["errors"])
    return payload["data"]


POST_CARD = "ref title slug excerpt publishedAt author { name }"

LIST_POSTS = f"""
query ListPosts($first: Int!) {{
  posts(orderBy: [createdAt_DESC], first: $first) {{ total items {{ {POST_CARD} }} }}
}}"""

SEARCH_POSTS = f"""
query Search($q: String!) {{
  searchPosts(query: $q, first: 5) {{ total items {{ {POST_CARD} }} }}
}}"""

# Route by slug: `id` is encrypted and expires, so it must never end up in a URL.
POST_BY_SLUG = """
query PostBySlug($slug: String!) {
  posts(where: { slug: $slug }, first: 1) {
    items { ref title slug body tags publishedAt updatedAt author { name } }
  }
}"""

CREATE_POST = """
mutation Create($data: PostCreateInput!) {
  createPost(data: $data) { id ref slug stage }
}"""

PUBLISH_POST = """
mutation Publish($id: ID!) {
  publishPost(id: $id) { ref slug stage publishedAt }
}"""


def post_by_slug(slug: str) -> dict[str, Any] | None:
    items = gql(POST_BY_SLUG, {"slug": slug})["posts"]["items"]
    return items[0] if items else None


def admin_demo() -> None:
    if not ADMIN_TOKEN:
        print("\n(admin) TESS_ADMIN_TOKEN not set: skipping create/publish and media upload")
        return

    slug = f"python-example-{int(time.time())}-{os.getpid()}"
    created = gql(
        CREATE_POST,
        {"data": {"title": "Hello from Python", "slug": slug,
                  "excerpt": "Created by examples/clients/python.",
                  "body": "Draft first, then published.", "tags": ["example", "python"]}},
        admin=True,
    )["createPost"]
    print(f"\n(admin) created draft {created['slug']} stage={created['stage']} ref={created['ref']}")
    # The id is only used immediately, inside this run; it is never stored.
    published = gql(PUBLISH_POST, {"id": created["id"]}, admin=True)["publishPost"]
    print(f"(admin) published {published['slug']} stage={published['stage']} at {published['publishedAt']}")

    # Media upload: raw body + Content-Type, file name in the query string.
    content = f"generated by the python example at {time.strftime('%Y-%m-%dT%H:%M:%S')}\n".encode()
    resp = requests.post(
        f"{TESS_URL}/media/upload",
        params={"fileName": "python-example.txt"},
        data=content,
        headers={"Content-Type": "text/plain", "Authorization": f"Bearer {ADMIN_TOKEN}"},
        timeout=30,
    )
    if resp.status_code >= 400:
        err = resp.json()
        print(f"(admin) upload failed: [{err.get('code')}] {err.get('error')}")
        return
    asset = resp.json()
    url = asset["url"] if asset["url"].startswith("http") else TESS_URL + asset["url"]
    print(f"(admin) uploaded {asset['fileName']} ({asset['mimeType']}, {asset['size']} bytes) ref={asset['ref']}")
    print(f"(admin) download: {url}")


def main() -> int:
    data = gql(LIST_POSTS, {"first": 10})["posts"]
    print(f"{data['total']} published post(s):")
    for p in data["items"]:
        print(f"  - [{p['ref']}] {p['title']} (/posts/{p['slug']}) by {p['author']['name'] if p['author'] else '?'}")

    result = gql(SEARCH_POSTS, {"q": "lambda"})["searchPosts"]
    print(f"\nsearch 'lambda': {result['total']} hit(s): {[p['slug'] for p in result['items']]}")

    if data["items"]:
        slug = data["items"][0]["slug"]
        post = post_by_slug(slug)
        print(f"\nby slug '{slug}': {post['title']} tags={post['tags']}\n  {post['body']}")
    print(f"by slug 'does-not-exist': {post_by_slug('does-not-exist')}")

    # Error handling: a malformed/expired id yields BAD_USER_INPUT / ID_EXPIRED.
    try:
        gql("query($id: ID!) { post(id: $id) { title } }", {"id": "not-a-real-id"})
    except GraphQLError as e:
        print(f"\nexpected error, code={e.code}: {e}")
    # Writes without a token are FORBIDDEN.
    try:
        gql(CREATE_POST, {"data": {"title": "nope"}})
    except GraphQLError as e:
        print(f"expected error, code={e.code}: {e}")

    admin_demo()
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except requests.RequestException as e:
        print(f"cannot reach {TESS_URL}: {e}", file=sys.stderr)
        sys.exit(1)

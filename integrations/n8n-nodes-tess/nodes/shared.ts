import { createHmac, timingSafeEqual } from "node:crypto";
import {
  NodeApiError,
  type IDataObject,
  type IExecuteFunctions,
  type IHookFunctions,
  type ILoadOptionsFunctions,
  type INodePropertyOptions,
  type JsonObject,
} from "n8n-workflow";

type Ctx = IExecuteFunctions | IHookFunctions | ILoadOptionsFunctions;

interface GraphQLResponse {
  data?: IDataObject | null;
  errors?: { message: string; extensions?: { code?: string } }[];
}

/** POSTs a GraphQL operation to Tess with the node's credential; throws on GraphQL errors. */
export async function tessGraphql(ctx: Ctx, query: string, variables: IDataObject = {}): Promise<IDataObject> {
  const credentials = await ctx.getCredentials("tessApi");
  const baseUrl = String(credentials.baseUrl).replace(/\/$/, "");
  let res: GraphQLResponse;
  try {
    res = (await ctx.helpers.httpRequestWithAuthentication.call(ctx, "tessApi", {
      method: "POST",
      url: `${baseUrl}/graphql`,
      body: { query, variables },
      json: true,
    })) as GraphQLResponse;
  } catch (error) {
    throw new NodeApiError(ctx.getNode(), error as JsonObject);
  }
  if (res.errors?.length) {
    const message = res.errors.map((e) => (e.extensions?.code ? `${e.message} (${e.extensions.code})` : e.message)).join("; ");
    throw new NodeApiError(ctx.getNode(), res as unknown as JsonObject, { message });
  }
  return res.data ?? {};
}

export interface ContentTypeInfo {
  apiId: string;
  pluralApiId: string;
  workflow: boolean;
  fields: { name: string; type: string }[];
}

export async function contentTypes(ctx: Ctx): Promise<ContentTypeInfo[]> {
  const data = await tessGraphql(ctx, "{ contentTypes { apiId pluralApiId workflow fields { name type } } }");
  return (data.contentTypes as ContentTypeInfo[]) ?? [];
}

export async function contentTypeOptions(this: ILoadOptionsFunctions): Promise<INodePropertyOptions[]> {
  return (await contentTypes(this)).map((t) => ({ name: t.apiId, value: t.apiId }));
}

export async function formOptions(this: ILoadOptionsFunctions): Promise<INodePropertyOptions[]> {
  const data = await tessGraphql(this, "{ forms { id title slug } }");
  return ((data.forms as IDataObject[]) ?? []).map((f) => ({ name: `${f.title} (${f.slug})`, value: f.id as string }));
}

export async function eventOptions(this: ILoadOptionsFunctions): Promise<INodePropertyOptions[]> {
  const data = await tessGraphql(this, "{ webhookEvents }");
  const events = ((data.webhookEvents as string[]) ?? []).filter((e) => e !== "webhook.ping");
  const subjects = [...new Set(events.map((e) => e.slice(0, e.lastIndexOf("."))))];
  return [
    { name: "Everything", value: "*" },
    ...subjects.map((s) => ({ name: `All ${s} events`, value: `${s}.*` })),
    ...events.map((e) => ({ name: e, value: e })),
  ];
}

const lowerFirst = (s: string) => s.charAt(0).toLowerCase() + s.slice(1);

/** GraphQL names generated by Tess for a content type (see crates/graphql/src/naming.rs). */
export function names(t: ContentTypeInfo) {
  return {
    single: lowerFirst(t.apiId),
    list: t.pluralApiId,
    create: `create${t.apiId}`,
    update: `update${t.apiId}`,
    delete: `delete${t.apiId}`,
    publish: `publish${t.apiId}`,
    unpublish: `unpublish${t.apiId}`,
    createInput: `${t.apiId}CreateInput`,
    updateInput: `${t.apiId}UpdateInput`,
    whereInput: `${t.apiId}WhereInput`,
  };
}

const SCALARS = new Set(["TEXT", "MARKDOWN", "INT", "FLOAT", "BOOLEAN", "DATETIME", "DATE", "JSON", "UUID", "ENUM"]);

/** Default selection: system fields and every scalar field. */
export function defaultSelection(t: ContentTypeInfo): string {
  const fields = t.fields.filter((f) => SCALARS.has(f.type)).map((f) => f.name);
  return ["id", "ref", "createdAt", "updatedAt", "publishedAt", "workflowStatus", ...fields].join(" ");
}

/**
 * Checks `X-Tess-Signature: t=<seconds>,v1=<hex HMAC-SHA256(secret, "t.body")>`,
 * rejecting signatures older than `toleranceSeconds`.
 */
export function verifySignature(secret: string, header: string | undefined, body: Buffer, toleranceSeconds = 300): boolean {
  if (!header) return false;
  const parts = Object.fromEntries(header.split(",").map((p) => p.split("=", 2) as [string, string]));
  const t = Number(parts.t);
  if (!Number.isFinite(t) || !parts.v1) return false;
  if (Math.abs(Date.now() / 1000 - t) > toleranceSeconds) return false;
  const expected = createHmac("sha256", secret).update(`${parts.t}.`).update(body).digest();
  const given = Buffer.from(parts.v1, "hex");
  return given.length === expected.length && timingSafeEqual(given, expected);
}

/** Replaces the origin of n8n's webhook URL by the one Tess must use (e.g. http://n8n:5678). */
export function rewriteOrigin(url: string, origin: string): string {
  if (!origin.trim()) return url;
  const u = new URL(url);
  const o = new URL(origin);
  u.protocol = o.protocol;
  u.host = o.host;
  return u.toString();
}

